// ===== Helpers
const qs = (sel, el = document) => el.querySelector(sel);
const qsa = (sel, el = document) => Array.from(el.querySelectorAll(sel));

const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

// ===== Footer year
qs("#year").textContent = new Date().getFullYear();

// ===== Scroll progress (top bar)
const progressBar = qs("#progressBar");
function updateProgress(){
  const doc = document.documentElement;
  const scrollTop = doc.scrollTop || document.body.scrollTop;
  const scrollHeight = (doc.scrollHeight || document.body.scrollHeight) - doc.clientHeight;
  const p = scrollHeight > 0 ? (scrollTop / scrollHeight) * 100 : 0;
  progressBar.style.width = `${p}%`;
}
window.addEventListener("scroll", updateProgress, { passive:true });
updateProgress();

// ===== Reveal on scroll (IntersectionObserver)
const revealEls = qsa(".reveal");
if (!prefersReducedMotion && "IntersectionObserver" in window){
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e) => {
      if (e.isIntersecting){
        e.target.classList.add("is-in");
        io.unobserve(e.target);
      }
    });
  }, { threshold: 0.12 });

  revealEls.forEach(el => io.observe(el));
} else {
  revealEls.forEach(el => el.classList.add("is-in"));
}

// ===== HERO video parallax
const hero = qs(".hero");
const heroVideo = qs(".hero__video");

function heroParallax(){
  if (!hero || !heroVideo || prefersReducedMotion) return;

  const r = hero.getBoundingClientRect();
  const p = Math.min(1, Math.max(0, (0 - r.top) / (r.height || 1)));
  const translate = p * 26;
  const scale = 1.06 + p * 0.03;

  heroVideo.style.transform = `translateY(${translate}px) scale(${scale})`;
}
window.addEventListener("scroll", heroParallax, { passive:true });
heroParallax();

// ===== Autoplay / Resume safety (abrir + scroll + voltar aba)
if (heroVideo){
  // garante condições clássicas de autoplay
  heroVideo.muted = true;
  heroVideo.playsInline = true;
  heroVideo.loop = true;

  const tryPlay = () => heroVideo.play().catch(() => {});

  // 1) ao abrir
  tryPlay();

  // 2) ao voltar pra aba
  document.addEventListener("visibilitychange", () => {
    if (!document.hidden) tryPlay();
  });

  // 3) ao voltar para a viewport (scroll desce/sobe)
  if ("IntersectionObserver" in window && hero){
    const heroIO = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) tryPlay();
      });
    }, { threshold: 0.35 });

    heroIO.observe(hero);
  }

  // 4) fallback: se o browser bloquear autoplay, destrava no primeiro gesto
  const unlock = () => tryPlay();
  window.addEventListener("pointerdown", unlock, { once:true });
  window.addEventListener("touchstart", unlock, { once:true });
  window.addEventListener("wheel", unlock, { once:true });
  window.addEventListener("keydown", unlock, { once:true });
}

// ===== Projects data (generated by scripts/build.py → assets/js/projects-data.js)
const projects = window.PROJECTS || [];

const list = qs("#projectList");
const preview = qs(".preview");
const previewImg = qs("#previewImg");
const previewTitle = qs("#previewTitle");
const previewTag = qs("#previewTag");

// preload only the first covers; the rest load on hover
projects.slice(0, 4).forEach(p => { if (p.img) { const i = new Image(); i.src = p.img; } });

function setPreview(p){
  if (!p) return;
  if (p.img){
    previewImg.src = p.img;
    previewImg.alt = p.title;
    previewImg.hidden = false;
  } else {
    previewImg.removeAttribute("src");
    previewImg.hidden = true;
  }
  previewTitle.textContent = p.title;
  previewTag.textContent = p.tag;
  preview.classList.add("is-active");
}

// Render
projects.forEach((p) => {
  const li = document.createElement("li");
  li.className = "project" + (p.link ? "" : " project--soon");

  const inner = `
    <span class="project__n">${p.n}</span>
    <span class="project__body">
      <span class="project__title">${p.title}</span>
      <span class="project__meta">${p.tag}</span>
    </span>
    <span class="project__cta">${p.link ? "Open" : "Soon"}</span>
  `;
  li.innerHTML = p.link
    ? `<a class="project__link" href="${p.link}">${inner}</a>`
    : `<div class="project__link" tabindex="0">${inner}</div>`;

  const target = li.firstElementChild;
  target.addEventListener("mouseenter", () => setPreview(p));
  target.addEventListener("focus", () => setPreview(p));

  target.addEventListener("mousemove", (ev) => {
    if (prefersReducedMotion) return;
    const rect = target.getBoundingClientRect();
    const t = (ev.clientX - rect.left) / (rect.width || 1);
    previewImg.style.transform = `translateX(${(t - 0.5) * 10}px) scale(1.12)`;
  });
  target.addEventListener("mouseleave", () => { previewImg.style.transform = ""; });

  list.appendChild(li);
});

// default
setPreview(projects[0]);
